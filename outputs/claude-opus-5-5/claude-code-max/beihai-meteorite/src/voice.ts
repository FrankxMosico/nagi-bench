/** Is the cue with this id active at time t? */
export function cueActive(id: string, t: number): boolean {
  const cue = voiceCues.find((c) => c.id === id);
  return Boolean(cue && t >= cue.start && t < cue.end);
}

/** Is any cue spoken by `speaker` (prefix match) active at t? */
export function speaking(speakerPrefix: string, t: number, kinds?: string[]): boolean {
  for (const c of voiceCues) {
    if (t >= c.start && t < c.end && c.speaker.startsWith(speakerPrefix) && (!kinds || kinds.includes(c.kind))) return true;
  }
  return false;
}
